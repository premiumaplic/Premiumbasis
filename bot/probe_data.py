"""Выдуманные данные для этапа 0 (замеры размеров ссылок и отправки).

Все имена придуманы. Настоящих учеников здесь нет и быть не должно.
"""

import random

FIRST_NAMES = [
    "Мухаммадали", "Азизбек", "Шахзода", "Мадина", "Жасур", "Камила",
    "Дилноза", "Саидакбар", "Нигора", "Бехруз", "Севара", "Отабек",
    "Малика", "Ислом", "Зарина", "Тимур", "Лола", "Абдурахмон",
    "Гулнора", "Шерзод",
]
LAST_INITIALS = "АБВГДЕЖЗИКЛМНОПРСТУХ"

# Вопросы недели 1–6 (языки) — тексты из технического задания.
QUESTIONS_RU = [
    ["Домашнее задание", "не сделано", "частично", "сделано с ошибками", "сделано хорошо"],
    ["Работа на уроке", "пассивен", "отвечает, когда спросят", "активно участвует", "помогает другим"],
    ["Новые слова", "не выучены", "выучена часть", "выучено большинство", "выучены все"],
    ["Грамматика темы", "не понял", "понимает с подсказкой", "применяет с ошибками", "применяет уверенно"],
    ["Говорение", "молчит", "отдельные слова", "простые фразы", "свободно для своего уровня"],
    ["Дисциплина", "мешал", "отвлекался", "нормально", "образцово"],
]

# Комментарий ровно 80 символов кириллицы — худший случай для размера.
LONG_COMMENT = ("Хорошо работал на уроке, но домашнее задание сдал поздно. "
                "Нужно повторить слова.")[:80].ljust(80, "ж")


def students(n: int, first_id: int = 1001):
    """[[id, "Имя Ф."], ...] — только имя и первая буква фамилии."""
    return [[first_id + i, f"{FIRST_NAMES[i % len(FIRST_NAMES)]} {LAST_INITIALS[i % len(LAST_INITIALS)]}."]
            for i in range(n)]


def form_input(n: int = 20, with_questions: bool = False, seed: int = 1) -> dict:
    """Данные, которые бот кладёт в ссылку кнопки недельного отчёта."""
    rnd = random.Random(seed)
    studs = students(n)
    data = {
        "v": 1,
        "gid": 12,
        "ts": 1795000000,
        "lang": "ru",
        "students": studs,
        # ответы прошлой недели: {id: [a1..a6]}
        "prev": {str(s[0]): [rnd.randint(0, 3) for _ in range(6)] for s in studs},
    }
    if with_questions:
        data["q"] = QUESTIONS_RU
    return data


def weekly_output(n: int = 20, comment: str = LONG_COMMENT, seed: int = 2) -> dict:
    """То, что форма недельного отчёта отправит боту (худший случай)."""
    rnd = random.Random(seed)
    return {
        "v": 1,
        "u": "3f6c2a9e-8b1d-4c7e-9a52-0d4e6b1f7c88",
        "t": "w",
        "g": 12,
        "w": "2026-11-16",
        "r": [[1001 + i, [rnd.randint(0, 3) for _ in range(6)], [1, 4], comment] for i in range(n)],
    }
